/**
 * Телефон във вертикално положение: сцените се подреждат в отделно проектно поле 600×1000
 * (вместо хоризонталното 1000×700), за да са героите и предметите по-едри (≈ ×1,7).
 * Само разположението е различно — логиката, мисиите и стъпките са същите.
 * Таблет, компютър и телефон хоризонтално използват досегашното поле.
 */
export const PW = 600
export const PH = 1000

/**
 * Телефон във вертикално положение — по размерите на целия екран (сцената на играта: ширина 900, височина 1200–2000
 * според формата на екрана). Телефоните са поне 1,7 пъти по-високи (375×667 → 1,78; 390×844 → 2,16);
 * таблетите вертикално — до 1,6 (768×1024 → 1,33; 800×1280 → 1,6). Не зависи от дължината на указанието.
 */
export const isPhonePortrait = (stage: { w: number; h: number }) => stage.w > 0 && stage.h >= stage.w * 1.7

type Pt = { x: number; y: number }

/**
 * Мисия 4: местата от stonesLayout (поле 1000×700) → вертикалното поле.
 * По ширина се свиват, по височина се разтягат; подредбата „близо / далече“ се запазва (вж. portrait.test.ts).
 */
export const stonePortrait = (p: Pt): Pt => ({ x: 300 + (p.x - 500) * 0.55, y: 150 + p.y * 1.17 })
