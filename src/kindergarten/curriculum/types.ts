/**
 * „Приказен математически парк“ — образователна структура (чист TypeScript, без React).
 *
 * Основа: образователно направление „Математика“ в държавния образователен стандарт за предучилищно
 * образование (Приложение № 2 към Наредба № 5 от 3 юни 2016 г.). Петте образователни ядра са взети от него.
 *
 * ВАЖНО: нормативните очаквани резултати се въвеждат ДОСЛОВНО от официалния текст и се маркират
 * като проверени (`status: 'verified'`) едва след сверка. Дотогава полето е „За проверка“.
 * Предложените дейности, цели и критерии са педагогически предложения на приложението —
 * те НЕ са нормативни изисквания и се показват отделно от нормативния текст.
 */

/** Възрастова група в детската градина. */
export type AgeGroupId = 1 | 2 | 3 | 4

/** Образователно ядро в направление „Математика“. */
export type CoreId = 'quantity' | 'measurement' | 'space' | 'time' | 'shapes'

/** Атракция в приказния парк — по една за всяко ядро. */
export type KgAttractionId = 'carousel' | 'giants-tower' | 'labyrinth' | 'wonder-clock' | 'shape-town'

/** Игрова механика — как детето взаимодейства с играта. */
export type Mechanic =
  | 'feed' // преместване на предмети към герои (съответствие, броене)
  | 'count-choose' // преброяване и избор на карта с точки
  | 'equalize' // изравняване на две групи чрез добавяне/премахване
  | 'split' // разделяне на количество на две части
  | 'sort-two' // разпределяне в две групи по признак
  | 'order' // подреждане в редица (сериация)
  | 'measure' // измерване с условна мярка
  | 'balance' // сравняване с везни
  | 'place-relative' // поставяне спрямо предмет (в, на, под, до)
  | 'find-position' // откриване по указание (ляво, дясно, пред, зад)
  | 'path' // движение по пътечка по указания
  | 'grid-map' // ориентиране в план/квадратна мрежа
  | 'choose-scene' // избор на картина, която отговаря на указание
  | 'sequence' // подреждане на събития във времето
  | 'match-pairs' // съпоставяне по двойки
  | 'calendar' // работа с календарна поредица
  | 'find-tap' // откриване и докосване на обекти
  | 'assemble' // сглобяване от части
  | 'mosaic' // запълване на силует с фигури
  | 'shape-in-world' // съпоставяне на фигура с предмет от околната среда

/** Нормативен текст от стандарта. */
export interface NormativeRef {
  /** 'pending' — още не е сверен с Приложение № 2; показва се „За проверка“. */
  status: 'pending' | 'verified'
  /** Дословен текст от стандарта (само при status === 'verified'). */
  text: string | null
  source: string
}

/** Връзка с тематично разпределение на програмна система (за бъдещо свързване). */
export interface ProgramLink {
  /** Наименование на програмната система / издателството. */
  system: string
  /** Тема или ситуация от тематичното разпределение. */
  theme: string
  /** Седмица в учебната година (ако е известна). */
  week?: number
}

/** Вид визуална подкрепа в играта. */
export type VisualSupport = 'ghost-slots' | 'counting-dots' | 'highlight-target' | 'demo-animation' | 'picture-cards' | 'arrows' | 'color-coding'

export interface ActivitySpec {
  id: string
  /** Име на играта, както се вижда от децата. */
  title: string
  core: CoreId
  group: AgeGroupId
  attraction: KgAttractionId
  /** Нормативен очакван резултат от стандарта — само дословно и след проверка. */
  normative: NormativeRef
  /** Конкретен резултат, към който е насочена играта (предложение на приложението). */
  targetOutcome: string
  /** Педагогическа цел (предложение на приложението). */
  pedagogicalGoal: string
  mechanic: Mechanic
  taskCount: { min: number; max: number; default: number }
  visualSupport: VisualSupport[]
  /** Кратки инструкции за детето (идентификатори на фрази в гласовата система или примерен текст). */
  instructions: string[]
  /** Критерий за успешно изпълнение. */
  successCriterion: string
  /** 'ready' — реализирана и проверена; 'planned' — подготвена като структура, не се показва като активна. */
  status: 'ready' | 'planned'
  /** Бъдещи връзки с тематичните разпределения на програмните системи. */
  programLinks: ProgramLink[]
}
